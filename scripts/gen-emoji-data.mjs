#!/usr/bin/env node
// 0.5.18 (EP-11/EP-27): build src/emoji/emojiData.ts — names + keywords only, no images.
// Sources (Unicode licence, https://www.unicode.org/license.txt):
//   scripts/data/emoji-test.txt              — order, groups, names (Unicode emoji data)
//   scripts/data/cldr-annotations-en-45.json — keywords (CLDR 45 annotations, modern, en)
// Native system emoji render the glyphs (no Twemoji / Noto / OpenMoji until Q8 is decided).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const MAX_E = 15.0; // skip newer emoji most system fonts cannot draw yet
const GROUP = {
  'Smileys & Emotion': 'smileys', 'People & Body': 'people', 'Animals & Nature': 'nature',
  'Food & Drink': 'food', 'Travel & Places': 'objects', 'Activities': 'objects', 'Objects': 'objects',
  'Symbols': 'symbols', 'Flags': 'symbols',
};
const ann = JSON.parse(readFileSync('scripts/data/cldr-annotations-en-45.json', 'utf8')).annotations.annotations;
const rows = [];
const seen = new Set();
let group = '';
for (const line of readFileSync('scripts/data/emoji-test.txt', 'utf8').split('\n')) {
  const g = line.match(/^# group: (.+)$/);
  if (g) { group = g[1].trim(); continue; }
  const m = line.match(/^([0-9A-F ]+);\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$/);
  if (!m || !GROUP[group]) continue;
  const cps = m[1].trim().split(/\s+/).map((h) => parseInt(h, 16));
  if (cps.some((c) => c >= 0x1f3fb && c <= 0x1f3ff)) continue; // skin tones: Q5 later
  if (Number(m[3]) > MAX_E) continue;
  const ch = String.fromCodePoint(...cps);
  const name = m[4].trim().replace(/^flag: /, 'flag ');
  const code = name.toLowerCase().replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
  if (!code || seen.has(code)) continue;
  seen.add(code);
  const a = ann[ch] ?? ann[ch.replace(/\uFE0F/g, '')];
  const kw = (a?.default ?? []).map((k) => k.toLowerCase()).filter((k) => k !== name.toLowerCase());
  rows.push([ch, code, kw.join(' ').replace(/\|/g, ' '), GROUP[group]].join('|'));
}
mkdirSync('src/emoji', { recursive: true });
writeFileSync('src/emoji/emojiData.ts',
`/* Generated by scripts/gen-emoji-data.mjs — do not edit.
 * Emoji names, groups and keywords from Unicode emoji-test.txt and CLDR 45 annotations (en).
 * Copyright © Unicode, Inc. Unicode Licence v3: https://www.unicode.org/license.txt
 * Rows: "char|shortcode|keywords|category". No glyph images: rendered with the system font. */
export const EMOJI_ROWS: readonly string[] = ${JSON.stringify(rows)};
`);
console.log(`src/emoji/emojiData.ts ${rows.length} emoji`);
